using System.Numerics;
using Content.Client.UserInterface.Controls;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.SprayPainter.UI;

[GenerateTypedNameReferences]
public sealed partial class SprayPainterGroup : BoxContainer
{
    public event Action<SpriteListData>? OnButtonPressed;

    private readonly ButtonGroup _buttonGroup = new();
    private readonly Dictionary<string, ContainerButton> _styleButtons = new();
    private string? _selectedStyle;

    public SprayPainterGroup()
    {
        RobustXamlLoader.Load(this);
    }

    public void PopulateList(List<SpriteListData> spriteList)
    {
        StyleGrid.RemoveAllChildren();
        _styleButtons.Clear();

        ContainerButton? firstButton = null;
        foreach (var data in spriteList)
        {
            var button = CreateStyleButton(data);
            _styleButtons[data.Style] = button;
            StyleGrid.AddChild(button);
            firstButton ??= button;
        }

        if (_selectedStyle != null && _styleButtons.TryGetValue(_selectedStyle, out var selectedButton))
        {
            selectedButton.Pressed = true;
        }
        else if (firstButton != null && spriteList.Count > 0)
        {
            firstButton.Pressed = true;
            _selectedStyle = spriteList[0].Style;
        }
    }

    public void SelectItemByStyle(string key)
    {
        _selectedStyle = key;
        if (_styleButtons.TryGetValue(key, out var button))
            button.Pressed = true;
    }

    private ContainerButton CreateStyleButton(SpriteListData data)
    {
        var name = Loc.GetString(
            $"spray-painter-style-{data.Group.ToLower()}-{data.Style.ToLower()}");

        var button = new ContainerButton
        {
            ToggleMode = true,
            Group = _buttonGroup,
            ToolTip = name,
            MinSize = new Vector2(130, 150),
            MaxSize = new Vector2(130, 150),
        };
        button.AddStyleClass(ListContainer.StyleClassListContainerButton);

        var box = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
            VerticalExpand = true,
        };

        var previewContainer = new PanelContainer
        {
            SetSize = new Vector2(96, 96),
            HorizontalAlignment = HAlignment.Center,
            VerticalAlignment = VAlignment.Center,
            Margin = new Thickness(0, 4, 0, 4),
        };

        var preview = new EntityPrototypeView
        {
            Scale = new Vector2(2f, 2f),
            Stretch = SpriteView.StretchMode.Fit,
            SetSize = new Vector2(96, 96),
        };
        preview.SetPrototype(data.Prototype);
        previewContainer.AddChild(preview);

        var label = new Label
        {
            Text = name,
            HorizontalAlignment = HAlignment.Center,
            VerticalAlignment = VAlignment.Center,
            HorizontalExpand = true,
            Margin = new Thickness(4, 0, 4, 4),
        };

        box.AddChild(previewContainer);
        box.AddChild(label);
        button.AddChild(box);

        button.OnPressed += _ =>
        {
            _selectedStyle = data.Style;
            OnButtonPressed?.Invoke(data);
        };

        return button;
    }
}
