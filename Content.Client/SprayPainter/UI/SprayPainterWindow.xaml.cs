using System.Linq;
using System.Numerics;
using Content.Client.UserInterface.Controls;
using Content.Shared.Decals;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;

namespace Content.Client.SprayPainter.UI;

[GenerateTypedNameReferences]
public sealed partial class SprayPainterWindow : DefaultWindow
{
    private const string PipeCategory = "__pipe__";
    private const string DecalCategory = "__decals__";

    [Dependency] private IEntitySystemManager _sysMan = default!;
    [Dependency] private ILocalizationManager _loc = default!;

    private readonly SpriteSystem _spriteSystem;

    public event Action<string, string>? OnSpritePicked;
    public event Action<int, bool>? OnTabChanged;
    public event Action<ProtoId<DecalPrototype>>? OnDecalChanged;
    public event Action<string>? OnSetPipeColor;
    public event Action<Color?>? OnDecalColorChanged;
    public event Action<int>? OnDecalAngleChanged;
    public event Action<bool>? OnDecalSnapChanged;
    public event Action<bool>? OnDecalColorPickerToggled;

    private GridContainer _colorGrid = default!;
    private readonly Dictionary<string, ContainerButton> _colorButtons = new();
    private Dictionary<string, Color> _currentPalette = new();
    private const string ColorLocKeyPrefix = "pipe-painter-color-";

    private Dictionary<string, Dictionary<string, EntProtoId>> _currentStylesByGroup = new();
    private Dictionary<string, List<string>> _currentGroupsByCategory = new();
    private List<string> _orderedCategories = new();

    private readonly Dictionary<string, SprayPainterGroup> _paintableControls = new();
    private readonly Dictionary<string, Button> _categoryButtons = new();
    private readonly Dictionary<string, Button> _subGroupButtons = new();
    private BoxContainer? _pipeControl;
    private string? _currentCategory;
    private string? _currentSubGroup;
    private ButtonGroup _categoryGroup = new();
    private ButtonGroup _subGroupGroup = new();

    private List<SprayPainterDecalEntry> _currentDecals = [];
    private SprayPainterDecals? _decalGrid;
    private SprayPainterDecalSettings? _decalSettings;

    private readonly SpriteSpecifier _colorEntryIconTexture = new SpriteSpecifier.Rsi(
        new ResPath("Structures/Piping/Atmospherics/pipe.rsi"),
        "pipeStraight");

    public SprayPainterWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _spriteSystem = _sysMan.GetEntitySystem<SpriteSystem>();
    }

    private string GetColorLocString(string? colorKey)
    {
        if (string.IsNullOrEmpty(colorKey))
            return Loc.GetString("pipe-painter-no-color-selected");

        var locKey = ColorLocKeyPrefix + colorKey;
        if (!_loc.TryGetString(locKey, out var locString))
            locString = colorKey;
        return locString;
    }

    private void OnStyleSelected(ListData data)
    {
        if (data is SpriteListData listData)
            OnSpritePicked?.Invoke(listData.Group, listData.Style);
    }

    private void OnColorPicked(string colorKey)
        => OnSetPipeColor?.Invoke(colorKey);

    public void PopulateCategories(
        Dictionary<string, Dictionary<string, EntProtoId>> stylesByGroup,
        Dictionary<string, List<string>> groupsByCategory,
        List<SprayPainterDecalEntry> decals)
    {
        var categoriesChanged = !_currentGroupsByCategory.Equals(groupsByCategory);
        var stylesChanged = !_currentStylesByGroup.Equals(stylesByGroup);
        var decalsChanged = !_currentDecals.Equals(decals);

        if (categoriesChanged)
        {
            _currentGroupsByCategory = groupsByCategory;
            _orderedCategories = groupsByCategory
                .Where(kv => kv.Value.Count > 0)
                .OrderBy(kv => kv.Key)
                .Select(kv => kv.Key)
                .ToList();
            BuildCategoryLayout();
        }

        if (categoriesChanged || stylesChanged)
        {
            _currentStylesByGroup = stylesByGroup;
            PopulateStyleGroups();
        }

        PopulateColors(_currentPalette);

        if (_decalGrid != null && (categoriesChanged || decalsChanged))
        {
            _currentDecals = decals;
            _decalGrid.PopulateDecals(decals, _spriteSystem);
        }

        RestoreCategorySelection();
    }

    private void BuildCategoryLayout()
    {
        CategoryList.RemoveAllChildren();
        _categoryButtons.Clear();
        _categoryGroup = new ButtonGroup();

        ClearSubTabs();
        ContentContainer.RemoveAllChildren();
        DecalControlsContainer.RemoveAllChildren();
        DecalControlsContainer.Visible = false;

        _paintableControls.Clear();
        _pipeControl = null;
        _decalGrid = null;
        _decalSettings = null;
        _currentCategory = null;
        _currentSubGroup = null;

        _colorButtons.Clear();
        _currentPalette.Clear();

        foreach (var categoryName in _orderedCategories)
        {
            if (!_currentGroupsByCategory.TryGetValue(categoryName, out var groups) || groups.Count == 0)
                continue;

            CategoryList.AddChild(CreateCategoryButton(
                Loc.GetString("spray-painter-tab-category-" + categoryName.ToLower()), categoryName));

            foreach (var group in groups)
            {
                var groupControl = new SprayPainterGroup();
                groupControl.OnButtonPressed += OnStyleSelected;
                _paintableControls[group] = groupControl;
            }
        }

        CreatePipeControl();
        CategoryList.AddChild(CreateCategoryButton(
            Loc.GetString("spray-painter-tab-category-pipes"), PipeCategory));

        EnsureDecalControls();
        CategoryList.AddChild(CreateCategoryButton(
            Loc.GetString("spray-painter-tab-category-decals"), DecalCategory));
    }

    private Button CreateCategoryButton(string text, string categoryName)
    {
        var button = new Button
        {
            Text = text,
            ToggleMode = true,
            Group = _categoryGroup,
            HorizontalExpand = true,
            ClipText = false,
        };
        var captured = categoryName;
        button.OnPressed += _ => SelectCategory(captured, true);
        _categoryButtons[categoryName] = button;
        return button;
    }

    private void CreatePipeControl()
    {
        _pipeControl = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
            VerticalExpand = true,
        };
        var label = new Label { Text = Loc.GetString("spray-painter-selected-color") };

        var scroll = new ScrollContainer { VerticalExpand = true, HorizontalExpand = true };
        _colorGrid = new GridContainer
        {
            Columns = 5,
            HorizontalExpand = true,
            VerticalExpand = true,
            HorizontalAlignment = HAlignment.Left
        };
        scroll.AddChild(_colorGrid);

        _pipeControl.AddChild(label);
        _pipeControl.AddChild(scroll);
    }

    private void EnsureDecalControls()
    {
        if (_decalGrid == null)
        {
            _decalGrid = new SprayPainterDecals();
            _decalGrid.OnDecalSelected += id => OnDecalChanged?.Invoke(id);
        }

        if (_decalSettings == null)
        {
            _decalSettings = new SprayPainterDecalSettings();
            _decalSettings.OnColorChanged += c => OnDecalColorChanged?.Invoke(c);
            _decalSettings.OnAngleChanged += a => OnDecalAngleChanged?.Invoke(a);
            _decalSettings.OnSnapChanged += s => OnDecalSnapChanged?.Invoke(s);
            _decalSettings.OnColorPickerToggled += t => OnDecalColorPickerToggled?.Invoke(t);
        }
    }

    private void PopulateStyleGroups()
    {
        foreach (var (group, styles) in _currentStylesByGroup)
        {
            if (!_paintableControls.TryGetValue(group, out var control))
                continue;

            var dataList = styles
                .Select(e => new SpriteListData(group, e.Key, e.Value, 0))
                .OrderBy(d => Loc.GetString($"spray-painter-style-{group.ToLower()}-{d.Style.ToLower()}"))
                .ToList();
            control.PopulateList(dataList);
        }
    }

    public void PopulateColors(Dictionary<string, Color> palette)
    {
        if (_colorGrid == null) return;

        if (_currentPalette.Equals(palette) && _colorButtons.Count > 0)
            return;

        _currentPalette = palette;
        _colorGrid.RemoveAllChildren();
        _colorButtons.Clear();

        foreach (var (colorKey, colorValue) in palette)
        {
            var locString = GetColorLocString(colorKey);

            var button = new ContainerButton
            {
                ToggleMode = true,
                ToolTip = locString,
                MinSize = new Vector2(100, 120),
                MaxSize = new Vector2(100, 120),
            };
            button.AddStyleClass(ListContainer.StyleClassListContainerButton);

            var box = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                HorizontalExpand = true,
                VerticalExpand = true,
            };

            var preview = new TextureRect
            {
                Texture = _spriteSystem.Frame0(_colorEntryIconTexture),
                Stretch = TextureRect.StretchMode.KeepAspectCentered,
                Modulate = colorValue,
                SetSize = new Vector2(64, 64),
                HorizontalAlignment = HAlignment.Center,
                VerticalAlignment = VAlignment.Center,
                Margin = new Thickness(0, 4, 0, 4),
            };

            var label = new Label
            {
                Text = locString,
                HorizontalAlignment = HAlignment.Center,
                VerticalAlignment = VAlignment.Center,
                HorizontalExpand = true,
                Margin = new Thickness(4, 0, 4, 4),
            };

            box.AddChild(preview);
            box.AddChild(label);
            button.AddChild(box);

            button.OnPressed += _ =>
            {
                foreach (var btn in _colorButtons.Values)
                    btn.Pressed = false;
                button.Pressed = true;
                OnColorPicked(colorKey);
            };

            _colorButtons[colorKey] = button;
            _colorGrid.AddChild(button);
        }
    }

    private void SelectCategory(string categoryName, bool notify)
    {
        _currentCategory = categoryName;
        ClearSubTabs();
        ContentContainer.RemoveAllChildren();
        DecalControlsContainer.Visible = false;

        if (categoryName == PipeCategory)
        {
            if (_pipeControl != null)
                ContentContainer.AddChild(_pipeControl);
        }
        else if (categoryName == DecalCategory)
        {
            if (_decalGrid != null)
                ContentContainer.AddChild(_decalGrid);

            if (_decalSettings != null)
            {
                DecalControlsContainer.RemoveAllChildren();
                DecalControlsContainer.AddChild(_decalSettings);
            }
            DecalControlsContainer.Visible = true;
        }
        else if (_currentGroupsByCategory.TryGetValue(categoryName, out var groups))
        {
            if (groups.Count == 1)
                ShowGroup(groups[0]);
            else if (groups.Count > 1)
                BuildSubTabs(groups);
        }

        if (notify)
        {
            var index = GetTabIndex(categoryName);
            if (index >= 0)
                OnTabChanged?.Invoke(index, categoryName == DecalCategory);
        }
    }

    private void BuildSubTabs(List<string> groups)
    {
        _subGroupGroup = new ButtonGroup();
        _subGroupButtons.Clear();

        var selectedGroup = _currentSubGroup != null && groups.Contains(_currentSubGroup)
            ? _currentSubGroup
            : groups[0];

        foreach (var group in groups)
        {
            var button = new Button
            {
                Text = Loc.GetString("spray-painter-tab-group-" + group.ToLower()),
                ToggleMode = true,
                Group = _subGroupGroup,
            };
            var captured = group;
            button.OnPressed += _ => ShowGroup(captured);
            _subGroupButtons[group] = button;
            SubTabBar.AddChild(button);

            if (group == selectedGroup)
                button.Pressed = true;
        }

        ShowGroup(selectedGroup);
    }

    private void ShowGroup(string group)
    {
        _currentSubGroup = group;
        ContentContainer.RemoveAllChildren();
        if (_paintableControls.TryGetValue(group, out var control))
            ContentContainer.AddChild(control);
    }

    private void ClearSubTabs()
    {
        SubTabBar.RemoveAllChildren();
        _subGroupButtons.Clear();
        _subGroupGroup = new ButtonGroup();
    }

    private void RestoreCategorySelection()
    {
        if (_currentCategory != null && _categoryButtons.TryGetValue(_currentCategory, out var btn))
        {
            btn.Pressed = true;
            SelectCategory(_currentCategory, false);
        }
        else if (_categoryButtons.Count > 0)
        {
            var firstKey = _categoryButtons.Keys.First();
            _categoryButtons[firstKey].Pressed = true;
            SelectCategory(firstKey, false);
        }
    }

    private int GetTabIndex(string categoryName)
    {
        if (categoryName == PipeCategory)
            return _orderedCategories.Count;
        if (categoryName == DecalCategory)
            return _orderedCategories.Count + 1;
        return _orderedCategories.IndexOf(categoryName);
    }

    public void SetSelectedStyles(Dictionary<string, string> selectedStyles)
    {
        foreach (var (group, style) in selectedStyles)
        {
            if (_paintableControls.TryGetValue(group, out var control))
                control.SelectItemByStyle(style);
        }
    }

    public void SelectColor(string color)
    {
        if (_colorButtons.TryGetValue(color, out var btn))
        {
            foreach (var b in _colorButtons.Values) b.Pressed = false;
            btn.Pressed = true;
        }
    }

    public void SetSelectedTab(int tab)
    {
        string? categoryName = null;
        if (tab >= 0 && tab < _orderedCategories.Count)
            categoryName = _orderedCategories[tab];
        else if (tab == _orderedCategories.Count)
            categoryName = PipeCategory;
        else if (tab == _orderedCategories.Count + 1)
            categoryName = DecalCategory;

        if (categoryName != null && _categoryButtons.TryGetValue(categoryName, out var button))
        {
            button.Pressed = true;
            SelectCategory(categoryName, false);
        }
    }

    public void SetSelectedDecal(string decal) => _decalGrid?.SetSelectedDecal(decal);
    public void SetDecalAngle(int angle) => _decalSettings?.SetAngle(angle);
    public void SetDecalColor(Color? color)
    {
        _decalSettings?.SetColor(color);
        _decalGrid?.SetColorModulate(color);
    }
    public void SetDecalSnap(bool snap) => _decalSettings?.SetSnap(snap);
    public void SetDecalColorPicker(bool enabled) => _decalSettings?.SetColorPicker(enabled);
}

public record SpriteListData(string Group, string Style, EntProtoId Prototype, int SelectedIndex) : ListData;
